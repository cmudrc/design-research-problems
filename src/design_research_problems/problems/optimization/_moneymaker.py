def _outer_diameter(inner_diameter: float) -> float:
    """Return the hose or cylinder outer diameter from the paper's linear fit.

    Args:
        inner_diameter: Hose or cylinder inner diameter in meters.

    Returns:
        Corresponding outer diameter in meters.
    """
    return _OUTER_DIAMETER_SLOPE * inner_diameter + _OUTER_DIAMETER_OFFSET


def _head_loss_major(length: float, velocity: float, diameter: float) -> float:
    """Return the Hazen-Williams major head loss in meters.

    Args:
        length: Pipe run length in meters.
        velocity: Mean fluid velocity in meters per second.
        diameter: Hydraulic diameter in meters.

    Returns:
        Major head-loss term in meters of water.
    """
    volumetric_flow = 0.25 * math.pi * diameter**2 * velocity
    numerator = 10.67 * length * volumetric_flow**1.85
    denominator = (_HAZEN_WILLIAMS**1.85) * diameter**4.87
    return float(numerator / denominator)


def _pump_head(force: float, diameter: float) -> float:
    """Return the hydraulic head generated by the piston force.

    Args:
        force: Applied piston force in newtons.
        diameter: Cylinder inner diameter in meters.

    Returns:
        Generated hydraulic head in meters.
    """
    piston_area = 0.25 * math.pi * diameter**2
    return force / (_WATER_DENSITY * _GRAVITY * piston_area)


